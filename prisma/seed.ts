function slots(group: string, list: Slot[]) {
  return list.map(([dayOfWeek, startTime, endTime, subject, type, building, room, teacher]) => ({
    groupName: group,
    dayOfWeek,
    startTime,
    endTime,
    subject,
    type,
    building,
    room,
    teacher,
  }));
}

