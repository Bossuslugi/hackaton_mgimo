type G = [subject: string, teacher: string, control: string, labs: number, midterm: number, attendance: number];

function grades(userId: string, list: G[]) {
  return list.map(([subject, teacher, controlType, labsScore, midtermScore, attendanceScore]) => ({
    userId,
    subject,
    teacher,
    controlType,
    labsScore,
    labsMax: 40,
    midtermScore,
    midtermMax: 40,
    attendanceScore,
    attendanceMax: 20,
    examMax: controlType === 'Экзамен' ? 30 : 0,
    currentTotal: computeTotal({ labsScore, midtermScore, attendanceScore }),
  }));
}

